/*
 * Build-time trig tables for the RSDKv4 PS1 port (docs/30 phase 2; from the Sonic CD port).
 *
 * RSDKv4's CalculateTrigAngles (RSDKv4/Math.cpp) fills sin/cos tables and a 64 KB atan table with
 * 65,536 atan2f calls at boot: ~26 s on the R3000A (no FPU, soft-float). This host program runs
 * the same loops (same types and expressions, as on PC) and prints the tables as C initializers
 * for ps1/trig_tables.inc, which Math.cpp includes on PS1 instead of computing them.
 * Usage: gen_trig > ps1/trig_tables.inc   (the Makefile does this)
 */
#include <math.h>
#include <stdio.h>

#ifndef M_PI
#define M_PI 3.14159265358979323846264338327950288
#endif

static int sinM[0x200], cosM[0x200], sin512[0x200], cos512[0x200], sin256[0x100], cos256[0x100];
static unsigned char atanT[0x100 * 0x100];

static void dump(const char *decl, const int *v, int n) {
    printf("%s = {", decl);
    for (int i = 0; i < n; ++i) printf("%s%d", i == 0 ? "\n    " : i % 16 ? ", " : ",\n    ", v[i]);
    printf("\n};\n");
}

int main(void) {
    for (int i = 0; i < 0x200; ++i) {
        sinM[i] = (sin((i / 256.0) * M_PI) * 4096.0);
        cosM[i] = (cos((i / 256.0) * M_PI) * 4096.0);
    }
    cosM[0x00] = 0x1000; cosM[0x80] = 0; cosM[0x100] = -0x1000; cosM[0x180] = 0;
    sinM[0x00] = 0; sinM[0x80] = 0x1000; sinM[0x100] = 0; sinM[0x180] = -0x1000;
    for (int i = 0; i < 0x200; ++i) {
        sin512[i] = (sinf((i / 256.0) * M_PI) * 512.0);
        cos512[i] = (cosf((i / 256.0) * M_PI) * 512.0);
    }
    cos512[0x00] = 0x200; cos512[0x80] = 0; cos512[0x100] = -0x200; cos512[0x180] = 0;
    sin512[0x00] = 0; sin512[0x80] = 0x200; sin512[0x100] = 0; sin512[0x180] = -0x200;
    for (int i = 0; i < 0x100; i++) {
        sin256[i] = (sin512[i * 2] >> 1);
        cos256[i] = (cos512[i * 2] >> 1);
    }
    for (int Y = 0; Y < 0x100; ++Y) {
        unsigned char *atan = &atanT[Y];
        for (int X = 0; X < 0x100; ++X) {
            float angle = atan2f(Y, X);
            *atan       = (angle * 40.743664f);
            atan += 0x100;
        }
    }
    printf("// Generated by tools/trig/gen_trig.c (RSDKv4 CalculateTrigAngles, run on the host). Do not edit.\n");
    dump("int sinM7LookupTable[0x200]", sinM, 0x200);
    dump("int cosM7LookupTable[0x200]", cosM, 0x200);
    dump("int sin512LookupTable[0x200]", sin512, 0x200);
    dump("int cos512LookupTable[0x200]", cos512, 0x200);
    dump("int sin256LookupTable[0x100]", sin256, 0x100);
    dump("int cos256LookupTable[0x100]", cos256, 0x100);
    // The atan table as its triangle x <= y (docs/30 "Mania lessons pass": -32,640 B of RAM in every stage). The other
    // half follows from truncation: T[x][y] = 63 - T[y][x] for x > y (atan2(y, x) + atan2(x, y) = 64 units, both
    // truncated), except the y = 0 column (exact angles: 0 and 64). Checked here for every entry; the build stops
    // otherwise. Index of T[a][b], a <= b: b * (b + 1) / 2 + a (RSDKv4/Math.cpp PS1ArcTan256).
    for (int x = 0; x < 0x100; ++x)
        for (int y = 0; y < 0x100; ++y) {
            int t = x <= y ? atanT[(x << 8) + y] : y == 0 ? 0 : 63 - atanT[(y << 8) + x];
            if (t != atanT[(x << 8) + y]) {
                fprintf(stderr, "gen_trig: atan triangle rule fails at %d,%d\n", x, y);
                return 1;
            }
        }
    printf("const byte arcTan256Triangle[0x100 * 0x101 / 2] = {");
    for (int b = 0, n = 0; b < 0x100; ++b)
        for (int a = 0; a <= b; ++a, ++n) printf("%s%d", n == 0 ? "\n    " : n % 32 ? "," : ",\n    ", atanT[(a << 8) + b]);
    printf("\n};\n");
    return 0;
}

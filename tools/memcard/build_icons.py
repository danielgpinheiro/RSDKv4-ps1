#!/usr/bin/env python3
"""Build-time memory card icons (phase 8): PS1/Memcard icons/*-mc-icon.png -> ps1/memcard_icons.h.

Each icon becomes a psyqo::MemoryCardFileSystem::Icon: a 16-colour BGR555 CLUT (index 0 =
transparent = 0x0000; visible black -> 0x8000) and one 16x16 4-bit frame (low nibble = left pixel).

Sources are pixel art: either native 16x16, or scaled up on a grid (the 1200x1200 files use 60 px
cells). The cell size is the GCD of every run of identical pixels along rows and columns, and
every cell must be one colour. Scaled icons are cropped to their opaque cells and centred in
16x16. Every icon is decoded back and compared with the source; a preview PNG is written.

Usage: build_icons.py [ICON_DIR] [OUT_HEADER] [PREVIEW_PNG]
  defaults: ../Memcard icons, ps1/memcard_icons.h, build/memcard_icons_preview.png
"""
import math, os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
ICONS = [  # (source file, C symbol, engine it belongs to)
    ('cd-mc-icon.png', 's_ps1McIconSonicCD', 'RSDKv3 / Sonic CD'),
    ('2-mc-icon.png', 's_ps1McIconSonic2', 'RSDKv4 / Sonic 1 & 2'),
    ('mania-mc-icon.png', 's_ps1McIconMania', 'RSDKv5 / Sonic Mania'),
]


def conv(rgb):
    r, g, b = rgb
    v = (r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)
    return v if v else 0x8000


def cell_grid(im):
    """The image as a grid of cells: (list of rows of RGBA-or-None, cell size)."""
    w, h = im.size
    px = im.load()
    key = lambda x, y: px[x, y] if px[x, y][3] >= 128 else None
    g = 0
    for y in range(h):
        run = 1
        for x in range(1, w + 1):
            if x < w and key(x, y) == key(x - 1, y):
                run += 1
            else:
                g = math.gcd(g, run); run = 1
    for x in range(w):
        run = 1
        for y in range(1, h + 1):
            if y < h and key(x, y) == key(x, y - 1):
                run += 1
            else:
                g = math.gcd(g, run); run = 1
    if w % g or h % g:
        sys.exit('ERROR: cell size %d does not divide %dx%d' % (g, w, h))
    cells = []
    for cy in range(h // g):
        row = []
        for cx in range(w // g):
            k = key(cx * g, cy * g)
            for y in range(cy * g, cy * g + g):
                for x in range(cx * g, cx * g + g):
                    if key(x, y) != k:
                        sys.exit('ERROR: cell (%d,%d) is not one colour' % (cx, cy))
            row.append(k)
        cells.append(row)
    return cells, g


def to_16x16(cells):
    h, w = len(cells), len(cells[0])
    if (w, h) == (16, 16):
        return cells
    opaque = [(x, y) for y in range(h) for x in range(w) if cells[y][x] is not None]
    x0, x1 = min(p[0] for p in opaque), max(p[0] for p in opaque)
    y0, y1 = min(p[1] for p in opaque), max(p[1] for p in opaque)
    bw, bh = x1 - x0 + 1, y1 - y0 + 1
    if bw > 16 or bh > 16:
        sys.exit('ERROR: opaque area %dx%d does not fit 16x16' % (bw, bh))
    ox, oy = (16 - bw) // 2, (16 - bh) // 2
    out = [[None] * 16 for _ in range(16)]
    for y in range(bh):
        for x in range(bw):
            out[oy + y][ox + x] = cells[y0 + y][x0 + x]
    return out


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, '..', 'Memcard icons')
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(REPO, 'ps1', 'memcard_icons.h')
    prev = sys.argv[3] if len(sys.argv) > 3 else os.path.join(REPO, 'build', 'memcard_icons_preview.png')
    lines = ['// Generated by tools/memcard/build_icons.py from PS1/Memcard icons -- do not edit.',
             '// psyqo::MemoryCardFileSystem::Icon: 16-colour BGR555 CLUT (0 = transparent) + one',
             '// 16x16 4-bit frame (low nibble = left pixel).',
             '#pragma once', '#include <psyqo/memory-card-filesystem.hh>', '']
    preview = Image.new('RGBA', (len(ICONS) * 136, 128), (96, 96, 96, 255))
    for n, (fname, sym, what) in enumerate(ICONS):
        im = Image.open(os.path.join(src, fname)).convert('RGBA')
        cells, cell = cell_grid(im)
        icon = to_16x16(cells)
        colours = []
        for row in icon:
            for c in row:
                if c is not None and c[:3] not in colours:
                    colours.append(c[:3])
        if len(colours) > 15:
            sys.exit('ERROR: %s has %d colours > 15' % (fname, len(colours)))
        clut = [0x0000] + [conv(c) for c in colours] + [0x0000] * (15 - len(colours))
        idx = [[0 if c is None else colours.index(c[:3]) + 1 for c in row] for row in icon]
        pixels = [idx[y][x] | (idx[y][x + 1] << 4) for y in range(16) for x in range(0, 16, 2)]
        # Self-check: decode the packed frame through the CLUT and compare with the source cells.
        for y in range(16):
            for x in range(16):
                i = (pixels[y * 8 + x // 2] >> (4 * (x & 1))) & 0xF
                want = 0x0000 if icon[y][x] is None else conv(icon[y][x][:3])
                assert clut[i] == want, '%s (%d,%d)' % (fname, x, y)
        small = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
        for y in range(16):
            for x in range(16):
                if icon[y][x] is not None:
                    small.putpixel((x, y), icon[y][x])
        preview.alpha_composite(small.resize((128, 128), Image.NEAREST), (n * 136 + 4, 0))
        lines.append('// %s: %s (%dx%d, cell %d px), %d colours + transparent' % (
            what, fname, im.size[0], im.size[1], cell, len(colours)))
        lines.append('static const psyqo::MemoryCardFileSystem::Icon %s = {' % sym)
        lines.append('    1,')
        lines.append('    {' + ', '.join('0x%04x' % v for v in clut) + '},')
        lines.append('    {{')
        for i in range(0, 128, 16):
            lines.append('        ' + ', '.join('0x%02x' % v for v in pixels[i:i + 16]) + ',')
        lines.append('    }},')
        lines.append('};')
        lines.append('')
        print('%s -> %s: %dx%d cell %d, %d colours + transparent, self-check exact' % (
            fname, sym, im.size[0], im.size[1], cell, len(colours)))
    open(out, 'w').write('\n'.join(lines))
    os.makedirs(os.path.dirname(prev), exist_ok=True)
    preview.save(prev)
    print('%s, preview %s' % (os.path.relpath(out, REPO), os.path.relpath(prev, REPO)))


if __name__ == '__main__':
    main()
